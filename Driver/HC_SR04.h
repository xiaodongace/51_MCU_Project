#ifndef __HC_SR04_H
#define __HC_SR04_H

/*========================================================================
 *  HC_SR04.h - HC-SR04 超声波测距
 *
 *  【2026-09-22 整体重写】改为**直接照抄**上课代码
 *    D:/TooL/Share_SyncHome/嵌入式4阶段/stc8上课代码/05_小车/05_小车_超声波
 *    Driver/Ultrasonic.c
 *  的实现方式（软件 Delay10us 数循环），不再用 Timer4 硬件计数。
 *
 *  为什么换回来（前两版都失败了，原因值得留着）：
 *    · 第 1 版：软件延时，但延时函数用 NOP 拼出来，实际 1.96us 却当成 1us 用
 *              -> 系数从 58 一路标定到 30，属于"用补丁掩盖根因"。
 *    · 第 2 版：改 Timer4 硬件计数，但误以为 T4_Load(0) 能清零计数器
 *              （T4H/T4L 是自动重装值），读数逐次累加，偏大 3 倍。
 *    · 第 3 版：改成 t0/t1 差值，理论上对了，但绕了一大圈。
 *  用户要求"直接抄"是对的：上课代码用的是**紧凑的 DJNZ 空转**，
 *  循环开销占比小、且整个"延时 + 计数"的组合是老师验证过的。
 *========================================================================*/

#include "GPIO.h"

/*------------------------------------------------------------------------
 *  引脚（本工程扩展板）
 *     TRIG = P2.4   推挽输出，发触发脉冲
 *     ECHO = P3.6   高阻输入，收回波
 *  ※ 上课代码用的是 P4.7 / P3.3（它那块"小车板"），**引脚不能照抄** ——
 *    本工程的真值表与 PCB 都是 P2.4 / P3.6（见《硬件真值表》1.12）。
 *------------------------------------------------------------------------*/
#define SR04_TRIG       P24
#define SR04_ECHO       P36

/*------------------------------------------------------------------------
 *  超时（单位 = "10us 的计次"，和上课代码一致）
 *
 *    SR04_EDGE_CNT_MAX  等 ECHO 起跳：500 x 10us = 5ms
 *                       模块没插 / 没回波时靠它兜住，不会死等
 *    SR04_ECHO_CNT_MAX  数 ECHO 高电平：3000 x 10us = 30ms
 *                       超过 30ms 说明目标太远（> 5 米）
 *------------------------------------------------------------------------*/
#define SR04_EDGE_CNT_MAX      500U
#define SR04_ECHO_CNT_MAX      3000U

/*------------------------------------------------------------------------
 *  距离换算：cm = cnt x 5 / 28
 *
 *  【物理公式】和上课代码一致：
 *       距离 = (高电平时间 ms x 34 cm/ms) / 2
 *            = 时间(us) x 0.034 / 2
 *            = 时间(us) / 58.82          （1cm 单程 = 2/34000 秒 = 58.82us 往返）
 *
 *  【每个 cnt 到底是多少 us】上课代码写 0.17，即认为 1 个 cnt = 10us。
 *    我按 STC8H 官方手册（STC8H_202605，第 983 页起"指令系统"的指令表）
 *    把它编译出来的汇编**逐条数时钟**，实际是 10.50us 而不是 10us：
 *
 *      一次 Delay10us 调用 = LCALL(2) + 78 x DJNZ(direct, 3 时钟) + RET(2)
 *                          = 2 + 234 + 2 = 238 时钟 = 9.92us
 *        "数回波"循环每迭代额外还要：
 *          JB/JNB P36(1) + CLR C(1) + MOV A,R7(1) + SUBB(1) + MOV A,R6(1)
 *          + SUBB(1) + JNC(1) + INC R7(1) + CJNE(3) + SJMP(3)
 *          = 14 时钟
 *      合计 = 238 + 14 = 252 时钟 = 10.50us @24MHz
 *
 *      ※ 交叉验证：触发脉冲是 SETB + 两次 Delay10us = 1 + 2x238 = 477 时钟
 *        = 19.9us，而上课代码注释写的就是"给个 2 个 10us"= 20us，吻合。
 *      ※ 手册对条件跳转的原文："当条件不满足时…执行时间为 1 个时钟；
 *        当条件满足时…则会发生跳转"，所以循环里那几条按 1 时钟算。
 *
 *  【结论】1cm 需要 58.82 / 10.50 = 5.60 个 cnt
 *       =>  cm = cnt / 5.60 = cnt x 5 / 28
 *
 *  为什么不用上课代码的 0.17：它隐含 5.88 cnt/cm，会**偏小约 5%**
 *  （20cm 量出来约 19cm）。5% 对"避障"够用，但对"量距离"就该修。
 *  修的依据是手册的指令周期 —— 这是可验证的，不是猜的。
 *  若真机上仍有固定比例偏差，用屏上的 RAW 一次校准：新系数 = RAW / 实际厘米数。
 *------------------------------------------------------------------------*/
#define SR04_CM_NUM            5U
#define SR04_CM_DEN            28U

/* 量程（cm）：和上课代码一致 —— 2 ~ 400 */
#define SR04_CM_MIN            2U
#define SR04_CM_MAX            400U

/* 中值滤波窗口：连续 5 次成功测量的原始计数取中值。
 * 上课代码没有滤波（它是按键触发、测一次就报），
 * 本工程是每 150ms 自动测一次，加一层中值可以吸收偶发的任务切换抖动。 */
#define SR04_FILTER_N          5U

/*========================================================================
 *  接口
 *========================================================================*/

/* 上电初始化：TRIG 推挽输出 + 拉低，ECHO 高阻输入 */
void SR04_Init(void);

/* 离开测距仪页面：拉低 TRIG。本版本不用定时器，所以只是"不发波"。 */
void SR04_Stop(void);

/* 测一次，返回距离（cm）。0 表示本次没测到（超时 / 量程外 / 模块没插）。
 * 失败原因可以从 SR04_LastRaw() 的数值看出来，见下面那张表。 */
u16  SR04_Measure(void);

/*------------------------------------------------------------------------
 *  【上机判读表】屏上同时显示 `距离 nn cm` 和 `RAW nnnn`。
 *  RAW = 本次测量的**原始计数**（cnt），任何一次测量都会更新它。
 *
 *     显示                 含义                       怎么办
 *     ------------------   ------------------------   ----------------------
 *     RAW 0               还没测过（刚进页面）        等一下
 *     RAW 500             等 ECHO 起跳超时(5ms)       模块没插 / 接线松 / TRIG 没输出
 *     RAW 3000            高电平超过 30ms             量程外或一直高（接线错）
 *     RAW 11 ~ 2241       正常测量（2~400cm）         按下面标定
 *
 *  标定（把尺子放好，一次就能算准）：
 *      新系数 = RAW ÷ 实际厘米数
 *  例：尺子放 25cm，RAW 显示 2350 -> 2350 / 25 = 94 -> 写成 94。
 *
 *  ※ 理论值：每个 cnt = 10.50us，1cm = 5.60 个 cnt（推导见上面 SR04_CM_NUM 那段）。
 *    如果实测仍偏大或偏小，用上面那个"新系数"一次校准即可。
 *------------------------------------------------------------------------*/
u16  SR04_LastRaw(void);

/* 清空中值滤波历史（进页面时调，避免把上一轮的残留值混进来） */
void SR04_ResetFilter(void);

#endif /* __HC_SR04_H */
