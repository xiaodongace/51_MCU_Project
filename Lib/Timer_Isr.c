/* 【2026-09-22 清理】原来这里还有 Timer1_ISR_Handler 和 Timer4_ISR_Handler 两个空壳
 * （函数体只有 "P66 = ~P66;" / "P63 = ~P63;"，是 STC 官方模板的默认写法）。
 * 本工程这两个中断都不会来：
 *   Timer1 —— 被 UART1 的波特率发生器占用（Lib/UART.c 里 ET1 = 0，不产生中断）；
 *   Timer4 —— 只当"自由回绕计数器"给超声波计时用（Driver/HC_SR04.c），也不开中断。
 * 删掉它们同时省下两个中断向量（每个 3 字节）。
 * 以后若真要用 Timer1/Timer4 中断，从 STC 官方库把函数体拷回即可。 */

/* 本项目接入的两个回调 */
extern void Nixie_Scan1ms(void);           /* Driver/NixieScan.c：每次刷一位数码管 */
extern volatile u32 g_sysTick;             /* App/App_Public.c：1ms 系统时钟 */

//========================================================================
// 函数: Timer2_ISR_Handler
// 描述: Timer2中断函数.
// 参数: none.
// 返回: none.
// 版本: V1.0, 2020-09-23
//========================================================================
void Timer2_ISR_Handler (void) interrupt TMR2_VECTOR		//进中断时已经清除标志
{
	/* 数码管扫描：每 1ms 刷一位，8 位轮一圈 8ms = 125Hz。
	 * 中断里只做这一件事，代码极短（约 20us）。 */
	Nixie_Scan1ms();
}

//========================================================================
// 函数: Timer3_ISR_Handler
// 描述: Timer3中断函数.
// 参数: none.
// 返回: none.
// 版本: V1.0, 2020-09-23
//========================================================================
void Timer3_ISR_Handler (void) interrupt TMR3_VECTOR		//进中断时已经清除标志
{
	/* 全项目统一的 1ms 系统时钟（《02》4.1 的"墙上的钟"）。
	 * 中断里只自增一次，其它模块用 SysTick_Get() 读差值算时间，
	 * 时间的推进与读取都不依赖任何等待。 */
	g_sysTick++;
}

